# 04_baseline.R ---------------------------------------------------------------
# Tunes the shrunken pitch-mix baseline on 2025 (trained on 2023-24) and writes
# models/baseline.json and docs/baseline_results.md.
#
# 2026 is the test season and is NOT scored here. It is scored once, in
# Phase 3, alongside the models, with the settings chosen below.

suppressPackageStartupMessages(library(dplyr))
source("R/constants.R")
source("R/clean.R")
source("R/cleaning_log.R")   # md_table()
source("R/baseline.R")

TRAIN_SEASONS <- 2023:2024
TUNE_SEASON <- 2025
KAPPA_GRID <- c(1, 5, 10, 25, 50, 100, 200, 400, 800)
DECAY_GRID <- c(0, 0.1, 0.25, 0.5, 0.75, 1)

con <- connect_duckdb()
targets <- load_targets(con, c(TRAIN_SEASONS, TUNE_SEASON))
DBI::dbDisconnect(con, shutdown = TRUE)
message("Loaded ", format(nrow(targets), big.mark = ","), " target pitches")

grid <- tidyr::crossing(kappa = KAPPA_GRID, decay = DECAY_GRID)
grid_results <- purrr::pmap_dfr(grid, function(kappa, decay) {
  res <- evaluate_baseline(targets, TRAIN_SEASONS, TUNE_SEASON, kappa, decay)
  summarise_scores(res$scored) |> mutate(kappa = kappa, decay = decay)
})
best <- slice_min(grid_results, log_loss, n = 1)
message(sprintf("Best: kappa = %s, decay = %s, log loss = %.4f", best$kappa, best$decay, best$log_loss))

variants <- list(
  "League mix for his hand and role (no pitcher info)" = list(kappa = Inf, decay = best$decay),
  "His own past mix, almost no shrinkage (kappa = 1)" = list(kappa = 1, decay = best$decay),
  "His own past mix, shrunk (tuned)" = list(kappa = best$kappa, decay = best$decay)
)
variant_runs <- lapply(variants, function(v)
  evaluate_baseline(targets, TRAIN_SEASONS, TUNE_SEASON, v$kappa, v$decay))
comparison <- purrr::imap_dfr(variant_runs, function(r, name)
  summarise_scores(r$scored) |> mutate(baseline = name, .before = 1))

# How much history each pitcher had going into 2025 decides how much shrinkage matters.
history_bins <- function(run) {
  hist <- run$probs |> distinct(pitcher, p_throws, role, N)
  run$scored |>
    left_join(hist, by = c("pitcher", "p_throws", "role")) |>
    mutate(history = cut(N, c(-Inf, 0, 300, 1500, Inf),
                         labels = c("none (new to MLB)", "1-300", "300-1,500", "1,500+")))
}
by_history <- bind_rows(
  summarise_scores(history_bins(variant_runs[[2]]), history) |> mutate(version = "almost no shrinkage"),
  summarise_scores(history_bins(variant_runs[[3]]), history) |> mutate(version = "shrunk")
) |>
  select(history, version, pitches, log_loss, top1) |>
  arrange(history, version)

tuned <- variant_runs[[3]]
by_role <- tuned$scored |> summarise_scores(role)

names_lu <- targets |> filter(game_year == TUNE_SEASON) |> distinct(pitcher, pitcher_name)
per_pitcher <- tuned$scored |>
  summarise_scores(pitcher) |>
  filter(pitches >= MIN_PITCHES_REPORTED) |>
  left_join(names_lu, by = "pitcher") |>
  distinct(pitcher, .keep_all = TRUE)

fmt <- function(df) mutate(df, across(any_of(c("log_loss")), ~ sprintf("%.3f", .x)),
                           across(any_of(c("top1")), ~ sprintf("%.1f%%", 100 * .x)))

dir.create("models", showWarnings = FALSE)
jsonlite::write_json(list(
  model = "shrunken pitch-mix baseline",
  kappa = best$kappa, decay = best$decay,
  prior_groups = "p_throws x role (SP/RP)",
  tuned_on = list(train = TRAIN_SEASONS, score = TUNE_SEASON),
  tune_log_loss = best$log_loss, tune_top1 = best$top1,
  created = as.character(Sys.time())
), "models/baseline.json", auto_unbox = TRUE, pretty = TRUE)

grid_table <- grid_results |>
  select(kappa, decay, log_loss) |>
  mutate(log_loss = sprintf("%.4f", log_loss)) |>
  tidyr::pivot_wider(names_from = decay, values_from = log_loss, names_prefix = "decay ")

lines <- c(
  "# Baseline results (tuning season)",
  "",
  sprintf("*Generated by `pipeline/04_baseline.R` on %s. Trained on %s, scored on %s. The 2026 test season is held back until Phase 3.*",
          Sys.Date(), paste(range(TRAIN_SEASONS), collapse = "-"), TUNE_SEASON),
  "",
  "## What the baseline is",
  "",
  "For every pitch, predict the pitcher's overall pitch mix from earlier seasons, ignoring count, batter and situation. Each pitcher's mix is pulled toward the league mix for pitchers with the same throwing hand and role (starter or reliever), and the pull is stronger the less history he has.",
  "",
  "## Headline",
  "",
  md_table(fmt(comparison)),
  "",
  "*Log loss: lower is better; it heavily punishes confident wrong answers. Top-1: how often the single most likely pitch was the one thrown.*",
  "",
  sprintf("Chosen settings: **kappa = %s** (each pitcher starts with %s pitches' worth of league mix) and **decay = %s** (the season two years back counts %s as much as last season).",
          best$kappa, best$kappa, best$decay, best$decay),
  "",
  "## Where shrinkage helps",
  "",
  "Grouped by how many pitches of history the pitcher had going in:",
  "",
  md_table(fmt(by_history)),
  "",
  "## By role",
  "",
  md_table(fmt(by_role)),
  "",
  sprintf("## Per pitcher (%d+ pitches in %s)", MIN_PITCHES_REPORTED, TUNE_SEASON),
  "",
  sprintf("%d pitchers qualify. Median log loss %.3f, median top-1 %.1f%%.",
          nrow(per_pitcher), median(per_pitcher$log_loss), 100 * median(per_pitcher$top1)),
  "",
  "Most predictable by the mix alone (usually one dominant pitch):",
  "",
  md_table(fmt(slice_min(per_pitcher, log_loss, n = 8) |> select(pitcher_name, pitches, log_loss, top1))),
  "",
  "Least predictable by the mix alone (deep repertoires or a changed mix):",
  "",
  md_table(fmt(slice_max(per_pitcher, log_loss, n = 8) |> select(pitcher_name, pitches, log_loss, top1))),
  "",
  "## Tuning grid (log loss on 2025)",
  "",
  md_table(grid_table),
  ""
)
writeLines(lines, "docs/baseline_results.md")
message("Wrote docs/baseline_results.md")
