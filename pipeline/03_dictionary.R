# 03_dictionary.R -------------------------------------------------------------
# Builds docs/data_dictionary.md from hand-written field notes plus missing
# rates measured on the regular-season raw data. Any Savant column without a
# note is flagged, so a schema change during the season gets noticed.

suppressPackageStartupMessages(library(dplyr))
source("R/constants.R")
source("R/clean.R")
source("R/cleaning_log.R")   # md_table()

notes <- readr::read_csv("docs/field_notes.csv", show_col_types = FALSE)
derived <- readr::read_csv("docs/derived_fields.csv", show_col_types = FALSE)

con <- connect_duckdb()
on.exit(DBI::dbDisconnect(con, shutdown = TRUE), add = TRUE)
invisible(DBI::dbExecute(con, sprintf(
  "CREATE VIEW raw AS SELECT * FROM read_parquet(%s, union_by_name = true, hive_partitioning = false)
   WHERE game_type = 'R'", raw_glob(SEASONS))))
raw_fields <- DBI::dbListFields(con, "raw")

missing_sql <- paste(sprintf(
  "AVG((NULLIF(NULLIF(TRIM(\"%s\"), ''), 'NA') IS NULL)::INT) AS \"%s\"",
  raw_fields, raw_fields), collapse = ",\n")
# game_year is the grouping column, so it is measured under another name.
missing <- DBI::dbGetQuery(con, sprintf(
  "SELECT game_year AS season, %s FROM raw GROUP BY game_year", missing_sql)) |>
  tidyr::pivot_longer(-season, names_to = "field", values_to = "missing") |>
  mutate(missing = sprintf("%.0f%%", 100 * missing)) |>
  tidyr::pivot_wider(names_from = season, values_from = missing, names_prefix = "missing_",
                     names_sort = TRUE)

undocumented <- setdiff(raw_fields, notes$field)
dropped_by_savant <- setdiff(notes$field, raw_fields)

clean_types <- CLEAN_COLUMNS
dictionary <- notes |>
  left_join(missing, by = "field") |>
  mutate(clean_type = unname(clean_types[field]),
         clean_type = ifelse(is.na(clean_type), "-", tolower(clean_type)))

section <- function(df) {
  df |>
    select(field, meaning, known_when, use, clean_type, starts_with("missing_")) |>
    md_table()
}

known_when_text <- c(
  "- **before pitch**: known before the pitcher starts his motion. Only these can be model features.",
  "- **after pitch**: measured on the pitch itself (velocity, location, result). Used in the report, never as a feature for the same pitch.",
  "- **after PA**: filled in when the plate appearance ends.",
  "- **future**: only knowable in hindsight. Never used.",
  "- **id**: identifiers and bookkeeping."
)
use_text <- c(
  "- **feature**: model input (Phase 2)",
  "- **target**: what the model predicts",
  "- **report**: shown in the matchup report",
  "- **filter / id**: used for cleaning or joining",
  "- **dropped**: not carried into the clean table"
)

groups <- c("Identifiers", "Game state", "Matchup", "Pitch", "Outcome", "Defense",
            "Leakage", "Deprecated", "Bookkeeping")
body <- unlist(lapply(groups, function(g) {
  rows <- filter(dictionary, group == g)
  if (!nrow(rows)) return(NULL)
  c(paste("###", g), "", section(rows), "")
}))

lines <- c(
  "# Data dictionary",
  "",
  sprintf("*Generated by `pipeline/03_dictionary.R` on %s from `docs/field_notes.csv` and `docs/derived_fields.csv`. Missing rates are for regular-season pitches in the raw Savant data.*", Sys.Date()),
  "",
  "Source: Baseball Savant Statcast search CSV, pulled one game day at a time with `baseballr::statcast_search()`. One row per pitch.",
  "",
  "## How to read the columns",
  "",
  "`known_when` is the leakage guard for the whole project:",
  "",
  known_when_text,
  "",
  "`use`:",
  "",
  use_text,
  "",
  "## Fields Savant provides",
  "",
  body,
  "## Fields added by the pipeline",
  "",
  md_table(derived),
  "",
  "## Schema checks",
  "",
  if (length(undocumented)) paste0("**Savant columns with no note (add them to field_notes.csv):** ",
                                   paste0("`", undocumented, "`", collapse = ", "))
  else "Every Savant column is documented.",
  "",
  if (length(dropped_by_savant)) paste0("Documented columns no longer in the feed: ",
                                        paste0("`", dropped_by_savant, "`", collapse = ", "))
  else "No documented column has disappeared from the feed.",
  ""
)
writeLines(lines, "docs/data_dictionary.md")
message("Wrote docs/data_dictionary.md (", nrow(dictionary), " Savant fields, ",
        length(undocumented), " undocumented)")
