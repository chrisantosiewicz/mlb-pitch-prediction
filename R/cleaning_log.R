# cleaning_log.R --------------------------------------------------------------
# Renders docs/cleaning_log.md from the summary that 02_clean.R saves.

md_table <- function(df) {
  df <- as.data.frame(df)
  # Years and ids are labels, not quantities: no thousands separator.
  label_cols <- grepl("year|season|game_pk", names(df))
  df[label_cols] <- lapply(df[label_cols], as.character)
  fmt <- function(x) if (is.numeric(x)) format(x, big.mark = ",", trim = TRUE) else as.character(x)
  body <- vapply(seq_len(nrow(df)), function(i) {
    paste0("| ", paste(vapply(df[i, , drop = FALSE], fmt, character(1)), collapse = " | "), " |")
  }, character(1))
  paste(c(paste0("| ", paste(names(df), collapse = " | "), " |"),
          paste0("|", strrep("---|", ncol(df))),
          body), collapse = "\n")
}

write_cleaning_log <- function(s, path) {
  steps <- s$step_counts |>
    tidyr::pivot_wider(id_cols = c(step, what), names_from = game_year, values_from = n,
                       names_sort = TRUE) |>
    dplyr::mutate(step = factor(step, levels = unique(s$step_counts$step))) |>
    dplyr::arrange(step)
  year_cols <- setdiff(names(steps), c("step", "what"))
  steps$Total <- rowSums(steps[year_cols], na.rm = TRUE)
  steps$step <- seq_len(nrow(steps))
  names(steps)[1:2] <- c("Step", "What it does")

  targets <- s$target_counts |>
    tidyr::pivot_wider(names_from = game_year, values_from = n, values_fill = 0, names_sort = TRUE)

  mix <- s$group_mix |>
    dplyr::group_by(game_year) |>
    dplyr::mutate(share = sprintf("%.1f%%", 100 * n / sum(n))) |>
    dplyr::ungroup() |>
    tidyr::pivot_wider(id_cols = pitch_group, names_from = game_year, values_from = share,
                       names_sort = TRUE) |>
    dplyr::mutate(pitch_group = factor(pitch_group, levels = PITCH_GROUPS)) |>
    dplyr::arrange(pitch_group) |>
    dplyr::mutate(name = PITCH_GROUP_NAMES[as.character(pitch_group)], .after = pitch_group)

  tto <- s$tto_check |>
    dplyr::mutate(game_year = as.character(game_year)) |>
    dplyr::mutate(savant_missing = sprintf("%.2f%%", 100 * savant_missing),
                  agree_with_pa_count = sprintf("%.1f%%", 100 * agree_with_pa_count))

  sweeper_note <- if (nrow(s$sweeper_shift) == 0) {
    "No pitcher with 200+ sliders/sweepers moved 50+ points between seasons."
  } else {
    paste0(nrow(s$sweeper_shift), " pitcher-season pairs moved 50+ points. The largest:\n\n",
           md_table(utils::head(s$sweeper_shift, 15)))
  }

  lines <- c(
    "# Cleaning log",
    "",
    sprintf("*Generated by `pipeline/02_clean.R` on %s. Re-running the pipeline regenerates this file.*", Sys.Date()),
    "",
    "## Row counts after each step",
    "",
    md_table(steps),
    "",
    "## Completeness against the MLB schedule",
    "",
    "Every completed regular-season game on the MLB Stats API schedule should have pitches in the clean table.",
    "",
    md_table(s$schedule_summary),
    "",
    if (nrow(s$missing_list)) paste0("Missing games:\n\n", md_table(utils::head(s$missing_list, 20)))
    else "No scheduled game is missing.",
    "",
    "## Which pitches are prediction targets",
    "",
    "Every remaining pitch stays in the clean table so it still counts as \"the previous pitch\" when sequences are built. Only rows with `target_status = model` are ever predicted or scored.",
    "",
    "- **model**: one of the 8 pitch groups",
    "- **non_pitch**: automatic balls/strikes from pitch-clock violations, pitchouts, intentional balls",
    "- **rare_type**: a real pitch outside the 8 groups (eephus, knuckleball, screwball, Savant's generic `FA`)",
    "- **unclassified**: Savant did not assign a pitch type",
    "",
    md_table(targets),
    "",
    "Most common excluded rows:",
    "",
    md_table(s$rare_types),
    "",
    "## Pitch-group mix by season (model targets only)",
    "",
    md_table(mix),
    "",
    "## Position players pitching (removed)",
    "",
    if (nrow(s$position_players)) md_table(s$position_players) else "None found.",
    "",
    sprintf("Pitchers with no MLB Stats API match (would be dropped by step 5): %d.", s$unmatched_pitchers),
    "",
    "## Times through the order",
    "",
    "Savant's `n_thruorder_pitcher` is compared with a version derived from the pitcher's own plate-appearance count in the game (TTO 1 = PAs 1-9, 2 = 10-18, 3 = 19-27, 4 = beyond). Disagreements are expected when a pinch hitter or substitution shifts the lineup; Savant's field counts times the *batter* has faced this pitcher, which is what a hitter's familiarity actually depends on.",
    "",
    md_table(tto),
    "",
    "## Slider / sweeper relabeling check",
    "",
    "Savant introduced the sweeper label in 2023 and has reclassified some pitchers since. A big jump in a pitcher's sweeper share is usually a label change, not a new pitch, so these pitchers are listed here and discussed in the limitations.",
    "",
    sweeper_note,
    ""
  )
  writeLines(lines, path)
}
