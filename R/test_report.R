# test_report.R ---------------------------------------------------------------
# Renders docs/test_results.md from the evaluation that 10_test_2026.R saves,
# so the report can be regenerated without refitting anything.

write_test_report <- function(ev, path) {
  fmt <- function(df) dplyr::mutate(df,
    dplyr::across(dplyr::any_of(c("log_loss", "family_log_loss", "L3 mix", "context model", "gain")),
                  ~ sprintf("%.3f", .x)),
    dplyr::across(dplyr::any_of(c("top1", "family_top1")), ~ sprintf("%.1f%%", 100 * .x)),
    dplyr::across(dplyr::any_of(c("difference", "lower", "upper")), ~ sprintf("%+.4f", .x)))

  pp <- ev$per_pitcher
  pp_summary <- tibble::tibble(
    pitchers = nrow(pp),
    `beat L1 (Phase 1 baseline)` = sprintf("%.0f%%", 100 * mean(pp$gain_vs_l1 > 0)),
    `beat L3 (best mix)` = sprintf("%.0f%%", 100 * mean(pp$gain_vs_l3 > 0)),
    `median gain vs L3` = sprintf("%.3f", stats::median(pp$gain_vs_l3))
  )
  pp_cols <- function(df) dplyr::transmute(df, pitcher_name, pitches,
                                           `L3 log loss` = sprintf("%.3f", l3),
                                           `model log loss` = sprintf("%.3f", app),
                                           gain = sprintf("%+.3f", gain_vs_l3))
  by_count <- ev$by_count
  names(by_count)[names(by_count) == "model"] <- "context model"

  writeLines(c(
    "# 2026 test results",
    "",
    sprintf("*Generated by `pipeline/10_test_2026.R` on %s. Models refit on 2023-2025 with settings fixed on 2025, scored once on 2026, as written in [preregistration.md](preregistration.md).*", Sys.Date()),
    "",
    "## Headline",
    "",
    md_table(fmt(ev$scores)),
    "",
    "## Which differences are real",
    "",
    "95% intervals from 500 bootstrap resamples of games. Negative = the first model is better; an interval that excludes zero is a real difference.",
    "",
    md_table(fmt(ev$comparisons)),
    "",
    sprintf("**Model the app uses (pre-registered decision rule): %s.**", ev$app_model),
    "",
    sprintf("**Pre-registered family-on-relabels rule kept: %s.**", if (isTRUE(ev$rule_kept)) "yes" else "no"),
    "",
    "## Calibration",
    "",
    "![Calibration by pitch type](figures/calibration_pitch.png)",
    "",
    "![Calibration by pitch family](figures/calibration_family.png)",
    "",
    sprintf("Average calibration error of the %s model by pitch type (weighted gap between predicted and actual frequency):", ev$app_model),
    "",
    md_table(ev$ece),
    "",
    sprintf("## Per pitcher (%d+ pitches in 2026)", MIN_PITCHES_REPORTED),
    "",
    md_table(pp_summary),
    "",
    "![Per-pitcher gain](figures/per_pitcher_gain.png)",
    "",
    "Biggest gains from context:",
    "",
    md_table(pp_cols(dplyr::slice_max(pp, gain_vs_l3, n = 10))),
    "",
    "Where context helps least or hurts:",
    "",
    md_table(pp_cols(dplyr::slice_min(pp, gain_vs_l3, n = 10))),
    "",
    "## By count",
    "",
    md_table(fmt(by_count)),
    "",
    "## By flag",
    "",
    md_table(fmt(ev$by_flag)),
    "",
    "## By role",
    "",
    md_table(fmt(ev$by_role)),
    ""
  ), path)
}
